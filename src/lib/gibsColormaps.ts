export type RgbValue = readonly [number, number, number, number]

const RGB_KEY = (r: number, g: number, b: number) => (r << 16) | (g << 8) | b

export interface ColorLookup {
  exact: Map<number, number>
  /** 32³ quantized nearest-value table for JPEG/PNG rounding. */
  quantized: Float32Array
}

export function buildColorLookup(entries: readonly RgbValue[]): ColorLookup {
  const exact = new Map<number, number>()
  const quantized = new Float32Array(32 * 32 * 32)
  quantized.fill(NaN)
  const dist = new Float32Array(quantized.length)
  dist.fill(1e9)

  for (const [r, g, b, v] of entries) {
    exact.set(RGB_KEY(r, g, b), v)
    const qr = r >> 3
    const qg = g >> 3
    const qb = b >> 3
    for (let dr = -1; dr <= 1; dr++) {
      for (let dg = -1; dg <= 1; dg++) {
        for (let db = -1; db <= 1; db++) {
          const rr = qr + dr
          const gg = qg + dg
          const bb = qb + db
          if (rr < 0 || gg < 0 || bb < 0 || rr > 31 || gg > 31 || bb > 31) continue
          const idx = (rr << 10) | (gg << 5) | bb
          const cx = (rr << 3) + 4
          const cy = (gg << 3) + 4
          const cz = (bb << 3) + 4
          const d = (cx - r) ** 2 + (cy - g) ** 2 + (cz - b) ** 2
          if (d < dist[idx]) {
            dist[idx] = d
            quantized[idx] = v
          }
        }
      }
    }
  }
  return { exact, quantized }
}

export function lookupColorValue(lut: ColorLookup, r: number, g: number, b: number, a: number): number {
  if (a < 20) return NaN
  if (r < 8 && g < 8 && b < 8) return NaN
  const hit = lut.exact.get(RGB_KEY(r, g, b))
  if (hit !== undefined) return hit
  return lut.quantized[(r >> 3 << 10) | (g >> 3 << 5) | (b >> 3)]
}

